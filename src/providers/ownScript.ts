/**
 * URL script-тега, из которого выполняется этот бандл. Нужен, чтобы
 * по умолчанию находить `dropbox-callback.html` (лежит рядом, в
 * `public/`, см. package.json → files) без того, чтобы владелец
 * сайта прописывал redirectUri руками — а заодно избавляет от
 * класса багов вроде "забыли поменять http на https в redirectUri
 * после переезда сайта на SSL": он теперь всегда берётся из того,
 * как страница ЭТОТ скрипт реально загрузила.
 *
 * Работает для сборки, подключённой как обычный `<script src="...">`
 * — то, как GrapesJS-плагины подключают повсеместно (включая наш
 * собственный демо-сайт): весь бандл выполняется как один синхронный
 * `<script>`, и `document.currentScript` весь это время стабильно
 * указывает именно на него, в каком бы внутреннем модуле его ни
 * прочитать — поэтому достаточно захватить значение один раз здесь,
 * при выполнении бандла (не внутри конструктора DropboxProvider —
 * к тому моменту, когда сайт вызывает `new DropboxProvider()` из
 * СВОЕГО отдельного <script>, currentScript уже указывает на
 * скрипт сайта, а не на наш).
 *
 * Для ESM-сборки, подключённой как `<script type="module">` или
 * через бандлер, `document.currentScript` по спеке всегда `null` —
 * в этом случае redirectUri нужно передать в опциях явно.
 */
export const OWN_SCRIPT_URL: string | null =
  typeof document !== 'undefined' ? ((document.currentScript as HTMLScriptElement | null)?.src ?? null) : null;
